let _dashLang = localStorage.getItem("autodev_dash_lang") || "ar";

function t(key) {
  return (I18N[_dashLang] && I18N[_dashLang][key]) || I18N.ar[key] || key;
}

function setLang(lang) {
  if (!I18N[lang]) return;
  _dashLang = lang;
  localStorage.setItem("autodev_dash_lang", lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  applyI18n();
}

function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const val = t(key);
    if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
      if (el.hasAttribute("placeholder")) el.placeholder = val;
    } else {
      el.textContent = val;
    }
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  // Update page title if set
  const titleEl = document.getElementById("pageTitle");
  if (titleEl && titleEl.dataset.pageKey) {
    titleEl.textContent = t(titleEl.dataset.pageKey);
  }
}

function getLang() { return _dashLang; }
window.I18N = I18N;
window.t = t;
window.setLang = setLang;
window.applyI18n = applyI18n;
window.getLang = getLang;
